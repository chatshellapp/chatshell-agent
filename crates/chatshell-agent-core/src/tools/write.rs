//! Write tool for LLM agents
//!
//! Creates new files or overwrites existing ones with provided content.
//! Automatically creates parent directories as needed.

use std::path::{Path, PathBuf};
use std::sync::Arc;

use rig::agent::tool::Tool;
use serde::{Deserialize, Serialize};
use serde_json::json;

use crate::path_policy;
use crate::tool_fs::{Fs, StdFs};

#[derive(Debug, Clone, Deserialize)]
pub struct WriteArgs {
    /// Absolute path to the file to write
    pub path: String,
    /// Complete content to write to the file
    pub content: String,
}

#[derive(Debug, thiserror::Error)]
#[error("Write error: {0}")]
pub struct WriteError(String);

fn default_fs() -> std::sync::Arc<dyn Fs> {
    std::sync::Arc::new(StdFs)
}

#[derive(Clone, Serialize, Deserialize)]
pub struct WriteTool {
    #[serde(skip_serializing_if = "Option::is_none")]
    project_root: Option<PathBuf>,
    #[serde(skip, default = "default_fs")]
    fs: Arc<dyn Fs>,
}

impl Default for WriteTool {
    fn default() -> Self {
        Self::new()
    }
}

impl WriteTool {
    pub fn new() -> Self {
        Self {
            project_root: None,
            fs: Arc::new(StdFs),
        }
    }

    pub fn with_project_root(root: PathBuf) -> Self {
        Self {
            project_root: Some(root),
            ..Self::new()
        }
    }

    /// Route IO through a custom [`Fs`] implementation.
    pub fn with_fs(mut self, fs: Arc<dyn Fs>) -> Self {
        self.fs = fs;
        self
    }
}

/// Detect write targets that were meant for other tools:
/// read-selector expressions (`src/foo.rs:50-100`) and semicolon-joined
/// multi-path lists. Refusing beats silently creating garbage files with
/// colons in their names (a known write-tool misfire class).
fn write_target_misfire(path: &str) -> Option<String> {
    if let Some((base, selector)) = path.rsplit_once(':')
        && !base.is_empty()
        && !selector.is_empty()
        && is_read_selector(selector)
    {
        return Some(format!(
            "Path looks like a read selector expression: {}. \
             The write tool takes a plain file path; to read a line range use the \
             read tool with offset/limit, and pass only the file path here.",
            path
        ));
    }
    let segments: Vec<&str> = path.split(';').map(str::trim).collect();
    if segments.len() > 1 && segments.iter().all(|s| s.contains('/') || s.contains('.')) {
        return Some(format!(
            "Path looks like a multi-path list joined with ';': {}. \
             The write tool writes exactly one file per call; split the list and \
             issue one write per path.",
            path
        ));
    }
    None
}
/// True when `selector` matches the read tool's line-selector tail grammar:
/// `raw` / `conflicts` / `N` / `N-M` / `N+K`, plus comma lists of those.
fn is_read_selector(selector: &str) -> bool {
    selector.split(',').all(|part| {
        let part = part.trim();
        if part == "raw" || part == "conflicts" {
            return true;
        }
        let digits = part.chars().take_while(|c| c.is_ascii_digit()).count();
        if digits == 0 {
            return false;
        }
        let rest = &part[digits..];
        rest.is_empty()
            || matches!(rest.chars().next(), Some('-' | '+'))
                && rest.len() > 1
                && rest[1..].chars().all(|c| c.is_ascii_digit())
    })
}

/// Generated-code detection: known generated filename patterns plus the
/// conventional `@generated` / `Code generated by` header markers (checked
fn is_generated_file(path: &Path, fs: &dyn Fs) -> bool {
    let name = path
        .file_name()
        .and_then(|n| n.to_str())
        .unwrap_or_default();
    const GENERATED_SUFFIXES: [&str; 6] = [
        ".pb.go",
        ".pb.cc",
        ".pb.h",
        "_pb2.py",
        "_pb2.pyi",
        ".generated.go",
    ];
    if GENERATED_SUFFIXES.iter().any(|s| name.ends_with(s)) {
        return true;
    }
    let Ok(bytes) = fs.read(path) else {
        return false;
    };
    let head = String::from_utf8_lossy(&bytes[..bytes.len().min(4096)]);
    head.contains("@generated") || head.contains("Code generated by")
}

impl Tool for WriteTool {
    const NAME: &'static str = "write";

    type Error = WriteError;
    type Args = WriteArgs;
    type Output = String;

    fn description(&self) -> String {
        "Create a new file or overwrite an existing file with the given content. \
                Parent directories are created automatically if they don't exist. \
                For modifying existing files prefer the `edit` tool over `write`, \
                as `edit` makes targeted changes while `write` replaces the entire file. \
                Use `write` for creating new files or when the entire content needs to be replaced."
            .to_string()
    }

    fn parameters(&self) -> serde_json::Value {
        json!({
            "type": "object",
            "properties": {
                "path": {
                    "type": "string",
                    "description": "Absolute path to the file to write"
                },
                "content": {
                    "type": "string",
                    "description": "The complete content to write to the file"
                }
            },
            "required": ["path", "content"]
        })
    }

    async fn call(
        &self,
        _context: &mut rig::agent::tool::ToolContext,
        args: Self::Args,
    ) -> Result<Self::Output, Self::Error> {
        tracing::info!(
            "🔧 [tool-call] write: path=\"{}\" content_len={}",
            args.path,
            args.content.len()
        );

        let path = Path::new(&args.path);
        let fs = &self.fs;

        path_policy::check_write(path, self.project_root.as_deref()).map_err(WriteError)?;

        // --- misfire guards: catch arguments that were meant for other tools ---
        if let Some(reason) = write_target_misfire(&args.path) {
            return Err(WriteError(reason));
        }

        let is_new = !fs.exists(path);

        // --- generated-file guard: refuse to clobber codegen output ---
        if !is_new && is_generated_file(path, fs.as_ref()) {
            return Err(WriteError(format!(
                "Refusing to overwrite generated file: {}. \
                 It is machine-generated output — regenerate it from its source \
                 (protoc, build tool, or the generator config) instead of editing it directly.",
                args.path
            )));
        }

        // Create parent directories if needed
        if let Some(parent) = path.parent()
            && !fs.exists(parent)
        {
            fs.create_dir_all(parent)
                .map_err(|e| WriteError(format!("Failed to create directories: {}", e)))?;
        }

        fs.write(path, args.content.as_bytes())
            .map_err(|e| WriteError(format!("Failed to write file: {}", e)))?;

        // Shebang scripts are made executable (best-effort; never fails the write).
        if args.content.starts_with("#!")
            && let Err(e) = fs.set_executable(path)
        {
            tracing::warn!("🔧 [write] could not mark executable: {}", e);
        }

        let made_executable = args.content.starts_with("#!");
        let line_count = args.content.lines().count();
        let action = if is_new { "Created" } else { "Wrote" };

        tracing::info!(
            "🔧 [tool-result] write: {} \"{}\" ({} lines, {} bytes)",
            action.to_lowercase(),
            args.path,
            line_count,
            args.content.len()
        );

        let anchor_header = crate::anchor_store::record_anchor(path, &args.content)
            .map(|tag| crate::edit_anchor::tag_header(&args.path, &tag));
        let exec_note = if made_executable {
            " [marked executable]"
        } else {
            ""
        };
        Ok(format!(
            "{} {} ({} lines, {} bytes){}{}",
            action,
            args.path,
            line_count,
            args.content.len(),
            exec_note,
            anchor_header
                .as_deref()
                .map(|header| format!("\n{header}"))
                .unwrap_or_default()
        ))
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn misfire_rejects_read_selector_paths() {
        assert!(write_target_misfire("src/foo.rs:50-100").is_some());
        assert!(write_target_misfire("notes.md:12").is_some());
        assert!(write_target_misfire("log.txt:raw").is_some());
        assert!(write_target_misfire("a.rs:1,b.rs:2").is_some());
        // Legit paths pass through.
        assert!(write_target_misfire("/tmp/plain file.txt").is_none());
        assert!(write_target_misfire("/tmp/2026-08-23T10:00.log").is_none()); // time-ish colon but non-selector tail
    }

    #[test]
    fn misfire_rejects_semicolon_lists() {
        assert!(write_target_misfire("src/a.rs;src/b.rs").is_some());
        assert!(write_target_misfire("one.txt; two.txt").is_some());
        assert!(write_target_misfire("/tmp/single.txt").is_none());
    }

    #[tokio::test]
    async fn generated_files_refuse_overwrite_but_allow_creation() {
        let dir = tempfile::tempdir().unwrap();
        let pb = dir.path().join("service_pb2.py");

        // Creating a new generated-named file is allowed (nothing to clobber).
        let tool = WriteTool::new();
        let args = WriteArgs {
            path: pb.to_string_lossy().to_string(),
            content: "x".to_string(),
        };
        <WriteTool as Tool>::call(&tool, &mut rig_test_context(), args.clone())
            .await
            .expect("creating a not-yet-existing generated-named file is fine");

        // Overwriting the existing generated file is refused with guidance.
        let err = <WriteTool as Tool>::call(&tool, &mut rig_test_context(), args)
            .await
            .expect_err("overwrite must be refused");
        assert!(err.to_string().contains("generated file"), "{err}");
        assert!(err.to_string().contains("regenerate"), "{err}");
    }

    #[tokio::test]
    async fn generated_marker_in_header_is_detected() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("handwritten.go");
        std::fs::write(
            &path,
            "// Code generated by protoc. DO NOT EDIT.\npackage main\n",
        )
        .unwrap();

        assert!(is_generated_file(&path, &StdFs));
    }

    #[tokio::test]
    async fn shebang_write_marks_executable() {
        let dir = tempfile::tempdir().unwrap();
        let script = dir.path().join("run.sh");
        let tool = WriteTool::new();
        let args = WriteArgs {
            path: script.to_string_lossy().to_string(),
            content: "#!/bin/bash\necho hi\n".to_string(),
        };
        let out = <WriteTool as Tool>::call(&tool, &mut rig_test_context(), args)
            .await
            .unwrap();

        assert!(out.contains("[marked executable]"), "{out}");
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            let mode = std::fs::metadata(&script).unwrap().permissions().mode();
            assert_ne!(mode & 0o111, 0, "exec bit set");
        }
    }

    /// Minimal ToolContext for direct `call` invocations in tests.
    fn rig_test_context() -> rig::agent::tool::ToolContext {
        rig::agent::tool::ToolContext::default()
    }
    #[test]
    fn test_write_tool_creation() {
        let tool = WriteTool::new();
        assert_eq!(WriteTool::NAME, "write");
        let _ = tool;
    }

    #[test]
    fn test_write_args() {
        let args: WriteArgs =
            serde_json::from_str(r#"{"path": "/tmp/test.txt", "content": "hello\nworld"}"#)
                .unwrap();
        assert_eq!(args.path, "/tmp/test.txt");
        assert_eq!(args.content, "hello\nworld");
    }
}
